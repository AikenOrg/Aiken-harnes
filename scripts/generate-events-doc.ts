/**
 * src/protocol/events.ts の zod スキーマからイベントペイロード一覧を生成する。
 *
 *   bun run docs:gen        # 書き出す
 *   bun run docs:gen:check  # 差分があれば失敗
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { z } from "zod";
import {
  EVENT_DESCRIPTIONS,
  eventSchemas,
  type CoreEventType,
} from "../src/protocol/events.ts";

const root = resolve(import.meta.dir, "..");
const outputPath = join(root, "docs/spec/06-events.generated.md");
const check = process.argv.includes("--check");

type JsonSchema = Record<string, unknown>;

function formatType(schema: unknown): string {
  const json = z.toJSONSchema(schema as z.ZodType, { io: "output" }) as JsonSchema;
  return describe(json);
}

function describe(json: JsonSchema): string {
  if (typeof json.const === "number" || typeof json.const === "string") {
    return JSON.stringify(json.const);
  }
  if (Array.isArray(json.enum)) {
    return json.enum.map((value) => JSON.stringify(value)).join(" | ");
  }
  if (Array.isArray(json.anyOf)) {
    return json.anyOf.map((value) => describe(value as JsonSchema)).join(" | ");
  }
  if (Array.isArray(json.oneOf)) {
    return json.oneOf.map((value) => describe(value as JsonSchema)).join(" | ");
  }
  if (json.type === "array") {
    return `${describe((json.items ?? {}) as JsonSchema)}[]`;
  }
  if (json.type === "object") {
    const properties = (json.properties ?? {}) as Record<string, JsonSchema>;
    const required = new Set((json.required ?? []) as string[]);
    const fields = Object.entries(properties).map(([key, value]) => {
      const optional = required.has(key) ? "" : "?";
      return `${key}${optional}: ${describe(value)}`;
    });
    return `{ ${fields.join(", ")} }`;
  }
  if (json.type === "integer") return "integer";
  if (json.type === "number") return "number";
  if (json.type === "boolean") return "boolean";
  if (json.type === "null") return "null";
  return "string";
}

const lines: string[] = [
  "# イベントペイロード一覧 (生成)",
  "",
  "<!-- AUTO-GENERATED by scripts/generate-events-doc.ts. 手で編集しない。 -->",
  "",
  "`src/protocol/events.ts` の zod スキーマが正。`bun run docs:gen` で再生成する。",
  "",
  "| イベント | 説明 | フィールド | 型 | 必須 |",
  "|---|---|---|---|---|",
];

const eventTypes = Object.keys(eventSchemas) as CoreEventType[];

for (const type of eventTypes) {
  const schema = eventSchemas[type];
  const description = EVENT_DESCRIPTIONS[type];
  const shape = (schema as z.ZodObject<z.ZodRawShape>).shape;
  const fields = Object.entries(shape);
  fields.forEach(([field, fieldSchema], index) => {
    const eventCell = index === 0 ? `\`${type}\`` : "";
    const descriptionCell = index === 0 ? description : "";
    const required = (fieldSchema as z.ZodType).isOptional() ? "" : "✓";
    const typeCell = formatType(fieldSchema).replaceAll("|", "\\|");
    const safeDescription = descriptionCell.replaceAll("|", "\\|");
    lines.push(
      `| ${eventCell} | ${safeDescription} | \`${field}\` | ${typeCell} | ${required} |`,
    );
  });
}

lines.push("");

const content = lines.join("\n");
const current = (() => {
  try {
    return readFileSync(outputPath, "utf8");
  } catch {
    return undefined;
  }
})();

if (check && current !== content) {
  console.error(`generated docs are stale: ${outputPath}`);
  console.error("run: bun run docs:gen");
  process.exit(1);
}

if (!check) {
  writeFileSync(outputPath, content);
  console.log(`generated: ${outputPath}`);
}
